#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.md (M10): every production dependency of the shipped web bundle
// (shared by all platforms) with version, license and copyright line, the full text of each
// license type once, then the bundled data files and the native-shell components.
// Usage: node scripts/gen-notices.mjs [--check]   (--check fails if the file is out of date)
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const raw = execFileSync(
  'pnpm',
  ['--filter', '@dasignature/web...', 'licenses', 'list', '--prod', '--json'],
  {
    cwd: root,
    encoding: 'utf8',
  },
);
const byLicense = JSON.parse(raw);
const pkgs = Object.values(byLicense)
  .flat()
  .filter((p) => !p.name.startsWith('@dasignature/'))
  .sort((a, b) => a.name.localeCompare(b.name));

const LICENSE_FILES = /^(licen[cs]e|copying|ofl)(\.(md|txt))?$/i;
function licenseText(dir) {
  const f = readdirSync(dir).find((n) => LICENSE_FILES.test(n));
  return f ? readFileSync(join(dir, f), 'utf8').replace(/\r\n?/g, '\n').trim() : '';
}
function copyright(text) {
  const lines = text.split('\n').filter((l) => /copyright\s+(\(c\)|©|\d{4})/i.test(l));
  return [...new Set(lines.map((l) => l.trim()))].slice(0, 3).join('; ');
}

const texts = new Map();
const rows = pkgs.map((p) => {
  const dir = p.paths[0];
  const text = dir && existsSync(dir) ? licenseText(dir) : '';
  if (text && !texts.has(p.license)) texts.set(p.license, { from: p.name, text });
  return `| ${p.name} | ${p.versions.join(', ')} | ${p.license} | ${copyright(text) || p.author || ''} |`;
});

const out = `# Third-party notices

DaSignature is licensed under Apache-2.0 (see LICENSE). It bundles the open-source components
below. This file is generated by \`node scripts/gen-notices.mjs\`. Do not edit by hand.

## Web bundle (all platforms: web/PWA, desktop, mobile)

| Package | Version | License | Copyright / author |
|---|---|---|---|
${rows.join('\n')}

## Bundled data files

| Component | Where | License |
|---|---|---|
| pdf.js standard fonts: Foxit fonts (FoxitDingbats, FoxitFixed*, FoxitSans*, FoxitSerif*, FoxitSymbol) | /pdfjs/standard_fonts | BSD-style license, Copyright 2014 PDFium Authors / Foxit Software Inc. (LICENSE_FOXIT in pdfjs-dist) |
| pdf.js standard fonts: Liberation Sans | /pdfjs/standard_fonts | SIL Open Font License 1.1 (LICENSE_LIBERATION in pdfjs-dist), Copyright (c) 2012 Red Hat, Inc. |
| pdf.js CMaps (Adobe CMap resources) | /pdfjs/cmaps | BSD-3-Clause, Copyright 1990-2019 Adobe |
| pdf.js image decoders (OpenJPEG, JBIG2, qcms) | /pdfjs/wasm, /pdfjs/iccs | as shipped in pdfjs-dist (Apache-2.0 / BSD-2-Clause / MIT) |
| Inter (UI and text-field font) | fonts | SIL Open Font License 1.1, Copyright (c) 2016 The Inter Project Authors |
| Signature script fonts (Alex Brush, Allura, Caveat, Dancing Script, Great Vibes, Homemade Apple, Sacramento, …) | fonts | SIL Open Font License 1.1 (see each @fontsource package above) |
| SQLite (WASM build, @sqlite.org/sqlite-wasm) | web storage | Public domain |

## Native shells

| Component | Platform | License |
|---|---|---|
| Tauri 2, wry, tao and the Rust crates they use | Windows, macOS, Linux | MIT or Apache-2.0 (per crate; \`cargo metadata\` in apps/desktop/src-tauri) |
| rusqlite / libsqlite3-sys | desktop | MIT |
| SQLCipher Community Edition | desktop, Android | BSD-3-Clause, Copyright (c) 2008-2024 Zetetic LLC |
| OpenSSL (vendored, Linux/macOS desktop) | desktop | Apache-2.0 |
| LibTomCrypt 1.18.2 (Windows desktop, SQLCipher crypto provider) | Windows | Public domain / WTFPL (dual) |
| keyring-rs | desktop | MIT or Apache-2.0 |
| WebView2 bootstrapper (Microsoft, installer only) | Windows | Microsoft Software License Terms (redistributable) |
| Capacitor 7 (@capacitor/core, @capacitor/android, @capacitor/ios) | Android, iOS | MIT |
| AndroidX libraries | Android | Apache-2.0 |
| sqlcipher-android (net.zetetic) | Android | BSD-3-Clause (SQLCipher) + Apache-2.0 (AOSP-derived Java code) |

## License texts

${[...texts.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([lic, { from, text }]) =>
      `### ${lic} (text as shipped by ${from})\n\n\`\`\`text\n${text}\n\`\`\``,
  )
  .join('\n\n')}
`;

const pdfjs = dirname(
  createRequire(join(root, 'packages/pdf/package.json')).resolve('pdfjs-dist/package.json'),
);
const fontLicense = (f) => readFileSync(join(pdfjs, 'standard_fonts', f), 'utf8').trim();
const outFull =
  out +
  `\n### pdf.js standard fonts: LICENSE_FOXIT\n\n\`\`\`text\n${fontLicense('LICENSE_FOXIT')}\n\`\`\`\n` +
  `\n### pdf.js standard fonts: LICENSE_LIBERATION\n\n\`\`\`text\n${fontLicense('LICENSE_LIBERATION')}\n\`\`\`\n`;
const file = join(root, 'THIRD_PARTY_NOTICES.md');
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== outFull) {
    console.error('THIRD_PARTY_NOTICES.md is out of date: run node scripts/gen-notices.mjs');
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES.md is up to date.');
} else {
  writeFileSync(file, outFull);
  console.log(`THIRD_PARTY_NOTICES.md: ${pkgs.length} packages, ${texts.size} license texts.`);
}
