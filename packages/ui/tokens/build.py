#!/usr/bin/env python3
"""Generate tokens.css, theme.css (Tailwind v4) and tailwind.preset.js from tokens.json.
Usage: python3 build.py   (no dependencies). Never hand-edit generated files."""
import json, math, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(HERE, "tokens.json")))
EXT = "app.dasignature"
HDR = "/* GENERATED by build.py from tokens.json - do not edit by hand. */\n"
items = lambda g: [(k, v) for k, v in g.items() if not k.startswith("$")]
colors = items(T["color"])
css = lambda k: T["color"][k]["$extensions"][EXT]["css"]
ALIAS = re.compile(r"^\{color\.([a-z0-9-]+)\}$")

def raw(k, mode):
    t = T["color"][k]
    return t["$value"] if mode == "light" else t["$extensions"][EXT].get("dark", t["$value"])

def css_value(k, mode):
    v = raw(k, mode); m = ALIAS.match(v)
    if m: return f"var({css(m.group(1))})"
    if v == "color-mix":
        mx = T["color"][k]["$extensions"][EXT]["mix"]
        return f"color-mix(in srgb, var({css(mx['of'])}) {mx['pct']}%, var({css(mx['into'])}))"
    return v

def is_hex(v): return re.fullmatch(r"#[0-9A-Fa-f]{6}", v) is not None

RULES = {"text-muted": "LIGHT RULE (PM #31): only on --bg/--surface; on --surface-2 use --text",
         "accent": "LIGHT RULE (PM #31): never text; fills/borders/focus/icons only",
         "success": "LIGHT RULE (PM #31): never text; use icon or --success-chip-bg + --text label"}

def color_block(mode, indent="  "):
    out = []
    for k, t in colors:
        v = css_value(k, mode)
        note = f" /* {RULES[k]} */" if (mode == "light" and k in RULES) else ""
        src = t["$extensions"][EXT]["source"]
        if src.startswith("spec") and not note: note = ""
        out.append(f"{indent}{css(k)}: {v};{note}")
    fl = T["elevation"]["float"]
    out.append(f"{indent}--elevation-float: {fl['$value'] if mode == 'light' else fl['$extensions'][EXT]['dark']};")
    out.append(f"{indent}color-scheme: {mode};")
    return "\n".join(out)

def spring_linear(k, c, m, dur_s, n=32):
    w = math.sqrt(k / m); z = c / (2 * math.sqrt(k * m)); wd = w * math.sqrt(1 - z * z); pts = []
    for i in range(n + 1):
        t = dur_s * i / n
        x = 1 - math.exp(-z * w * t) * (math.cos(wd * t) + z * w / wd * math.sin(wd * t))
        pts.append("1" if i == n else (f"{x:.4f}".rstrip("0").rstrip(".") or "0"))
    return "linear(" + ", ".join(pts) + ")"

fam = lambda L: ", ".join(f'"{f}"' if " " in f else f for f in L)
ty = [(k, t) for k, t in items(T["typography"]) if t["$type"] == "typography"]
WORDMARK = T["typography"]["wordmark-tracking"]["$value"]
dur = {k: t["$value"] for k, t in items(T["motion"]["duration"])}
sp = T["motion"]["easing"]["spring"]; spp = sp["$extensions"][EXT]["spring"]
SPRING = spring_linear(spp["stiffness"], spp["damping"], spp["mass"], int(dur["sheet"][:-2]) / 1000)
cb = lambda a: "cubic-bezier(" + ", ".join(str(x) for x in a) + ")"
SIZE = dict(items(T["size"]))

st = ["  /* Brand primitives (Sec 11) - for logo/lockup only */"]
st += [f"  --brand-{k}: {t['$value']};" for k, t in items(T["primitive"])]
st += ["  /* Signature ink colors (SPEC 7.2, PM #44) - theme-independent content colors, >= 7:1 on --pdf-page; never UI chrome */"]
st += [f"  {t['$extensions'][EXT]['css']}: {t['$value']};" for k, t in items(T["ink"])]
st += ["  /* Typography (Sec 8.2): Inter variable, bundled locally */",
       f"  --font-sans: {fam(T['font']['family']['sans']['$value'])};",
       f"  --font-mono: {fam(T['font']['family']['mono']['$value'])};"]
st += [f"  --font-weight-{k}: {t['$value']};" for k, t in items(T["font"]["weight"])]
for k, t in ty:
    v = t["$value"]
    st += [f"  --font-size-{k}: {v['fontSize']};", f"  --line-height-{k}: {v['lineHeight']};",
           f"  --tracking-{k}: {v['letterSpacing']};", f"  --font-weight-{k}: {v['fontWeight']};"]
st.append(f"  --tracking-wordmark: {WORDMARK};")
st.append("  /* Spacing: 4 pt grid */")
st += [f"  --space-{k}: {t['$value']};" for k, t in items(T["space"])]
st.append("  /* Sizes. Hit targets (PM #16, #52): 44 px default/coarse pointer, 32 px fine pointer, at any width */")
st += [f"  --size-{k}: {t['$value']};" for k, t in SIZE.items()]
st.append("  /* Radius */")
st += [f"  --radius-{k}: {t['$value']};" for k, t in items(T["radius"])]
st.append("  /* Motion (150-200 ms ease-out; spring sheets) */")
st += [f"  --motion-{k}: {v};" for k, v in dur.items()]
st += [f"  --motion-easing: {cb(T['motion']['easing']['out']['$value'])};",
       f"  --motion-spring: {cb(sp['$value'])}; /* fallback; upgraded to a linear() spring below */",
       "  --elevation-none: none;"]
STATIC = "\n".join(st)
TARGET_MEDIA = "\n".join(f"@media {m['query']} {{\n  :root {{ --size-target: {m['value']}; }}\n}}"
                         for m in SIZE["target"]["$extensions"][EXT]["media"])
RM = "--motion-fast: 0ms; --motion-base: 0ms; --motion-sheet: 0ms; --motion-spring: linear;"
KILL = """animation-duration: 0.01ms !important; animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important; scroll-behavior: auto !important;"""

tokens_css = HDR + f"""/* DaSignature design tokens.
   Theme: no data-theme (or "system") = follow OS; data-theme="light" | "dark" on <html> forces a theme.
   SPEC Sec 8.2 hex values are verbatim (verified by check_contrast.py). Added tokens are aliases of
   spec/brand colors, never new hues. Pairing rules: see contrast-report.md and README.md (PM decision #31). */

:root {{
{STATIC}
}}

/* Hit target keys on the primary pointer alone, at any viewport width (PM #52).
   Default 44 px (no pointer info), coarse 44 px, fine 32 px. Hybrid devices follow their primary pointer. */
{TARGET_MEDIA}

/* ---------- Light (default) ---------- */
:root,
[data-theme="light"] {{
{color_block("light")}
}}

/* ---------- Dark (explicit) ---------- */
[data-theme="dark"] {{
{color_block("dark")}
}}

/* ---------- Dark (system: no explicit light/dark) ---------- */
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]):not([data-theme="dark"]) {{
{color_block("dark", "    ")}
  }}
}}

/* Spring easing via CSS linear() where supported (Chrome 113+, Safari 17.2+, Firefox 112+) */
@supports (transition-timing-function: linear(0, 1)) {{
  :root {{ --motion-spring: {SPRING}; }}
}}

/* ---------- Reduced motion: motion OFF (Sec 8.2, A11Y) ---------- */
@media (prefers-reduced-motion: reduce) {{
  :root {{ {RM} }}
  *, *::before, *::after {{
    {KILL}
  }}
}}
/* In-app override if Settings ever exposes it: <html data-motion="reduce"> */
[data-motion="reduce"] {{ {RM} }}
[data-motion="reduce"] *, [data-motion="reduce"] *::before, [data-motion="reduce"] *::after {{
    {KILL}
}}

/* ---------- Base ---------- */
html {{
  background: var(--bg); color: var(--text);
  font-family: var(--font-sans); font-size: 100%; /* respect user font size / dynamic type */
  -webkit-font-smoothing: antialiased; text-rendering: optimizeLegibility;
}}
:focus-visible {{ outline: var(--size-focus-ring-width) solid var(--focus-ring); outline-offset: var(--size-focus-ring-offset); }}

/* ---------- Selection on the PDF page (Sec 7.4, PM #33) ----------
   Gold 2 px outline + 1 px white inner halo; handles = page-white fill + navy pdf-ink stroke. */
.ds-selection {{
  outline: var(--size-selection-width) solid var(--selection); outline-offset: 0;
  box-shadow: inset 0 0 0 var(--size-selection-halo-width) var(--selection-halo); /* halo, not elevation */
}}
.ds-selection-handle {{
  width: var(--size-handle); height: var(--size-handle); background: var(--pdf-page);
  border: var(--size-handle-stroke) solid var(--pdf-ink); border-radius: 2px;
}}
"""

# Tailwind key aliases matching the Engineer's existing preset (xs..2xl) + semantic names
SIZE_ALIAS = {"caption": "xs", "body-sm": "sm", "body": "base", "title": "lg", "headline": "xl", "display": "2xl"}
HEAVY = ("title", "headline", "display")

# ---------- Tailwind v4 ----------
v4 = [HDR + "/* Tailwind CSS v4 only. Usage: @import \"tailwindcss\"; @import \"./tokens.css\"; @import \"./theme.css\"; */",
      '@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));', "",
      "/* Static values are literal here to avoid self-referencing custom properties with tokens.css. */",
      "@theme inline {", "  --color-*: initial;", "  --color-transparent: transparent;", "  --color-current: currentColor;"]
v4 += [f"  --color-{k}: var({css(k)});" for k, _ in colors]
v4 += [f"  --color-brand-{k}: var(--brand-{k});" for k, _ in items(T["primitive"])]
v4 += [f"  --color-ink-{k}: var(--ink-{k});" for k, _ in items(T["ink"])]
v4 += [f"  --font-sans: {fam(T['font']['family']['sans']['$value'])};",
       f"  --font-mono: {fam(T['font']['family']['mono']['$value'])};", "  --font-weight-*: initial;"]
v4 += [f"  --font-weight-{'normal' if k == 'regular' else k}: {t['$value']};" for k, t in items(T["font"]["weight"])]
v4.append("  --text-*: initial;")
for k, t in ty:
    for n in (k, SIZE_ALIAS[k]):
        v4 += [f"  --text-{n}: var(--font-size-{k});", f"  --text-{n}--line-height: var(--line-height-{k});",
               f"  --text-{n}--letter-spacing: var(--tracking-{k});"]
        if k in HEAVY: v4.append(f"  --text-{n}--font-weight: var(--font-weight-{k});")
v4 += [f"  --tracking-wordmark: {WORDMARK};", "  --spacing: var(--space-1); /* 4 px unit */",
       "  --spacing-touch: var(--size-touch);", "  --spacing-target: var(--size-target);", "  --radius-*: initial;"]
v4 += [f"  --radius-{k}: {t['$value']};" for k, t in items(T["radius"])]
v4 += ["  --radius-full: 9999px;", "  --radius-none: 0;", "  --shadow-*: initial;", "  --shadow-float: var(--elevation-float);",
       "  --ease-*: initial;", "  --ease-out: var(--motion-easing);", "  --ease-spring: var(--motion-spring);",
       "  --default-transition-duration: var(--motion-base);", "  --default-transition-timing-function: var(--motion-easing);",
       "  --breakpoint-*: initial;"]
v4 += [f"  --breakpoint-{k}: {t['$value']};" for k, t in items(T["breakpoint"])]
v4 += ["}", "", "/* Named durations (v4 has no duration theme namespace) */"]
v4 += [f"@utility duration-{k} {{ transition-duration: var(--motion-{k}); }}" for k in dur]
theme_css = "\n".join(v4) + "\n"

# ---------- Tailwind v3 preset ----------
def twcolor(k):
    v = raw(k, "light")
    # spec hex tokens use plain var(); opacity modifiers are intentionally not offered on colors (contrast).
    return f"var({css(k)})"
c3 = {"transparent": "transparent", "current": "currentColor", "inherit": "inherit"}
c3.update({k: twcolor(k) for k, _ in colors})
c3["brand"] = {k: f"var(--brand-{k})" for k, _ in items(T["primitive"])}
c3["ink"] = {k: f"var(--ink-{k})" for k, _ in items(T["ink"])}
fs3 = {}
for k, t in ty:
    s = [f"var(--font-size-{k})", {"lineHeight": f"var(--line-height-{k})", "letterSpacing": f"var(--tracking-{k})"}]
    if k in HEAVY: s[1]["fontWeight"] = f"var(--font-weight-{k})"
    fs3[SIZE_ALIAS[k]] = s; fs3[k] = s
preset = {
  "darkMode": ["selector", '[data-theme="dark"]'],
  "theme": {
    "screens": {k: t["$value"] for k, t in items(T["breakpoint"])},
    "colors": c3,
    "fontFamily": {"sans": ["var(--font-sans)"], "mono": ["var(--font-mono)"]},
    "fontSize": fs3,
    "fontWeight": {"normal": "var(--font-weight-regular)", "medium": "var(--font-weight-medium)", "semibold": "var(--font-weight-semibold)"},
    "borderRadius": {"none": "0", **{k: f"var(--radius-{k})" for k, _ in items(T["radius"])}, "DEFAULT": "var(--radius-input)", "full": "9999px"},
    "boxShadow": {"none": "none", "float": "var(--elevation-float)"},
    "extend": {
      "spacing": {**{k: f"var(--space-{k})" for k, _ in items(T["space"])}, "touch": "var(--size-touch)", "target": "var(--size-target)"},
      "minWidth": {"touch": "var(--size-touch)", "target": "var(--size-target)"},
      "minHeight": {"touch": "var(--size-touch)", "target": "var(--size-target)"},
      "borderColor": {"DEFAULT": "var(--border)"},
      "outlineColor": {"focus": "var(--focus-ring)", "selection": "var(--selection)"},
      "outlineWidth": {"selection": "var(--size-selection-width)"},
      "ringColor": {"DEFAULT": "var(--focus-ring)"},
      "letterSpacing": {"wordmark": "var(--tracking-wordmark)"},
      "transitionDuration": {**{k: f"var(--motion-{k})" for k in dur}, "DEFAULT": "var(--motion-base)"},
      "transitionTimingFunction": {"DEFAULT": "var(--motion-easing)", "out": "var(--motion-easing)", "spring": "var(--motion-spring)"},
    },
  },
}
preset_js = ("// GENERATED by build.py from tokens.json - do not edit by hand.\n"
  "// Tailwind CSS v3.4.x preset (repo pins tailwindcss ^3.4.17). Usage: presets: [require('./tailwind.preset.js')]\n"
  "// Import tokens.css once (e.g. @import '@dasignature/ui/tokens.css' in index.css). Tailwind v4: use theme.css instead.\n"
  "/** @type {import('tailwindcss').Config} */\nmodule.exports = " + json.dumps(preset, indent=2) + ";\n")

for name, body in (("tokens.css", tokens_css), ("theme.css", theme_css), ("tailwind.preset.js", preset_js)):
    open(os.path.join(HERE, name), "w").write(body); print("wrote", name)
